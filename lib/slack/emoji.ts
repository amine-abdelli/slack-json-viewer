/** Strips Slack skin-tone / alias suffixes, e.g. `+1::skin-tone-3`. */
export function normalizeShortcode(name: string): string {
  return name.split("::")[0].replace(/^:|:$/g, "").trim();
}

/** Resolves a Slack shortcode to its unicode glyph, or `null` if unknown. */
export function emojiFromShortcode(name: string): string | null {
  const key = normalizeShortcode(name);
  return EMOJI[key] ?? null;
}

/** Resolves a hex codepoint sequence ("1f600" / "1f1eb-1f1f7") to a glyph. */
export function emojiFromUnicode(unicode?: string): string | null {
  if (!unicode) return null;
  try {
    return unicode
      .split("-")
      .map((cp) => String.fromCodePoint(parseInt(cp, 16)))
      .join("");
  } catch {
    return null;
  }
}

/** Best-effort rendering for an emoji element. */
export function renderEmoji(name?: string, unicode?: string): string {
  return (
    emojiFromUnicode(unicode) ??
    (name ? emojiFromShortcode(name) : null) ??
    (name ? `:${normalizeShortcode(name)}:` : "")
  );
}

